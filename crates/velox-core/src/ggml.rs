    #[test]
    fn decoders_match_gguf_py() {
        // Seeds follow the reference script's type order, which REFERENCE keeps.
        for (seed, (t, stats, picks)) in REFERENCE.iter().enumerate() {
            let data = blocks(*t, seed as u64 + 1);
            let mut v = Vec::new();
            decode_rows_into(*t, &data, 512, 0, 1, &mut v);
            let close = |got: f64, want: f64| (got - want).abs() <= 1e-9 * (1.0 + want.abs());
            let sum: f64 = v.iter().map(|&x| f64::from(x)).sum();
            let abs: f64 = v.iter().map(|&x| f64::from(x).abs()).sum();
            let weighted: f64 = v
                .iter()
                .enumerate()
                .map(|(i, &x)| f64::from(x) * (i + 1) as f64)
                .sum();
            assert!(close(sum, stats[0]), "{t:?} sum {sum} want {}", stats[0]);
            assert!(close(abs, stats[1]), "{t:?} abs {abs} want {}", stats[1]);
            assert!(
                close(weighted, stats[2]),
                "{t:?} weighted {weighted} want {}",
                stats[2]
            );
            for (&i, &want) in PICKS.iter().zip(picks) {
                assert_eq!(v[i], want, "{t:?} value {i}");
            }
        }
    }

    #[test]
    fn ids_and_sizes_round_trip() {
        for t in GgmlType::ALL {
            assert_eq!(GgmlType::from_gguf_id(t.gguf_id()), Some(t));
            assert_eq!(GgmlType::from_name(t.name()), Some(t));
        }
        // bits per weight from ggml: IQ3_S 3.4375, IQ4_XS 4.25, Q4_K 4.5.
        assert_eq!(GgmlType::Iq3S.block_bytes() * 8, 3 * 256 + 112);
        assert_eq!(GgmlType::Iq4Xs.block_bytes() * 8, 4 * 256 + 64);
        assert_eq!(GgmlType::Q4K.block_bytes() * 8, 4 * 256 + 128);
        // Q6_K 6.5625, Q8_0 8.5, IQ4_NL 4.5, Q2_0 2.25.
        assert_eq!(GgmlType::Q6K.block_bytes() * 8, 6 * 256 + 144);
        assert_eq!(GgmlType::Q8_0.block_bytes() * 8, 8 * 32 + 16);
        assert_eq!(GgmlType::Iq4Nl.block_bytes() * 8, 4 * 32 + 16);
        assert_eq!(GgmlType::Q2_0.block_bytes() * 8, 2 * 64 + 16);
    }
