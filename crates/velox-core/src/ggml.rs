//! llama.cpp (GGML) block-quantized weights, stored as GGUF stores them (`ggml_block_v1`).
//!
//! A row of a `[n, k]` matrix is `k / t.block_values()` consecutive blocks of one [`GgmlType`]
//! (256-value super-blocks for the K-quants and i-quants, 32 or 64 values for the legacy-style
//! types); a parent is its rows back to back, so a payload is the GGUF tensor's bytes unchanged.
//! Rows are independent, which lets an importer reorder them without touching any code.
//!
//! [`decode_block`] follows ggml's `dequantize_row_*` (ggml-quants.c, MIT) operation for
//! operation in f32, so the oracle and the kernels decode the same values. The lookup tables at
//! the end are generated from ggml-common.h.

/// GGML block types velox executes.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum GgmlType {
    Q2K,
    Q4K,
    Iq1M,
    Iq2Xxs,
    Iq2Xs,
    Iq2S,
    Iq3Xxs,
    Iq3S,
    Iq4Xs,
    Q2_0,
    Iq4Nl,
    Q6K,
    Q8_0,
}

impl GgmlType {
    /// Kernel format codes are positions here (`VELOX_FMT_GGML_BASE + i`): append new types.
    pub const ALL: [GgmlType; 13] = [
        GgmlType::Q2K,
        GgmlType::Q4K,
        GgmlType::Iq1M,
        GgmlType::Iq2Xxs,
        GgmlType::Iq2Xs,
        GgmlType::Iq2S,
        GgmlType::Iq3Xxs,
        GgmlType::Iq3S,
        GgmlType::Iq4Xs,
        GgmlType::Q2_0,
        GgmlType::Iq4Nl,
        GgmlType::Q6K,
        GgmlType::Q8_0,
    ];

    /// Container format name (with layout `ggml_block_v1`).
    pub fn name(self) -> &'static str {
        match self {
            GgmlType::Q2K => "ggml_q2_k",
            GgmlType::Q4K => "ggml_q4_k",
            GgmlType::Iq1M => "ggml_iq1_m",
            GgmlType::Iq2Xxs => "ggml_iq2_xxs",
            GgmlType::Iq2Xs => "ggml_iq2_xs",
            GgmlType::Iq2S => "ggml_iq2_s",
            GgmlType::Iq3Xxs => "ggml_iq3_xxs",
            GgmlType::Iq3S => "ggml_iq3_s",
            GgmlType::Iq4Xs => "ggml_iq4_xs",
            GgmlType::Q2_0 => "ggml_q2_0",
            GgmlType::Iq4Nl => "ggml_iq4_nl",
            GgmlType::Q6K => "ggml_q6_k",
            GgmlType::Q8_0 => "ggml_q8_0",
        }
    }

    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|t| t.name() == name)
    }

    /// `ggml_type` id in GGUF tensor infos.
    pub fn gguf_id(self) -> u32 {
        match self {
            GgmlType::Q2K => 10,
            GgmlType::Q4K => 12,
            GgmlType::Iq2Xxs => 16,
            GgmlType::Iq2Xs => 17,
            GgmlType::Iq3Xxs => 18,
            GgmlType::Iq3S => 21,
            GgmlType::Iq2S => 22,
            GgmlType::Iq4Xs => 23,
            GgmlType::Iq1M => 29,
            GgmlType::Q8_0 => 8,
            GgmlType::Q6K => 14,
            GgmlType::Iq4Nl => 20,
            GgmlType::Q2_0 => 42,
        }
    }

    pub fn from_gguf_id(id: u32) -> Option<Self> {
        Self::ALL.into_iter().find(|t| t.gguf_id() == id)
    }

    /// Values per block.
    pub fn block_values(self) -> usize {
        match self {
            GgmlType::Q2_0 => 64,
            GgmlType::Iq4Nl | GgmlType::Q8_0 => 32,
            _ => 256,
        }
    }

    /// Bytes per block of [`GgmlType::block_values`] values.
    pub fn block_bytes(self) -> usize {
        match self {
            GgmlType::Q2K => 84,
            GgmlType::Q4K => 144,
            GgmlType::Iq1M => 56,
            GgmlType::Iq2Xxs => 66,
            GgmlType::Iq2Xs => 74,
            GgmlType::Iq2S => 82,
            GgmlType::Iq3Xxs => 98,
            GgmlType::Iq3S => 110,
            GgmlType::Iq4Xs => 136,
            GgmlType::Q2_0 => 18,
            GgmlType::Iq4Nl => 18,
            GgmlType::Q6K => 210,
            GgmlType::Q8_0 => 34,
        }
    }

    /// Bytes of one row of `k` values (`k` a multiple of [`GgmlType::block_values`]).
    pub fn row_bytes(self, k: usize) -> usize {
        k / self.block_values() * self.block_bytes()
    }
}

fn f16(b: &[u8], at: usize) -> f32 {
    crate::format::f16_to_f32(u16::from_le_bytes([b[at], b[at + 1]]))
}

fn u16_at(b: &[u8], at: usize) -> u16 {
    u16::from_le_bytes([b[at], b[at + 1]])
}

fn u32_at(b: &[u8], at: usize) -> u32 {
    u32::from_le_bytes([b[at], b[at + 1], b[at + 2], b[at + 3]])
}

/// Byte `j` of a little-endian grid entry.
fn grid_byte(entry: u64, j: usize) -> u8 {
    (entry >> (8 * j)) as u8
}

fn sign(signs: u8, j: usize) -> f32 {
    if signs & (1 << j) != 0 {
        -1.0
    } else {
        1.0
    }
}

/// ggml `get_scale_min_k4`: 6-bit scale and min `j` of a Q4_K block's 12 scale bytes.
fn scale_min_k4(j: usize, q: &[u8]) -> (u8, u8) {
    if j < 4 {
        (q[j] & 63, q[j + 4] & 63)
    } else {
        (
            (q[j + 4] & 0xf) | ((q[j - 4] >> 6) << 4),
            (q[j + 4] >> 4) | ((q[j] >> 6) << 4),
        )
    }
}

/// Decodes one block (`t.block_bytes()` bytes) into `t.block_values()` values.
pub fn decode_block(t: GgmlType, x: &[u8], y: &mut [f32]) {
    let y = &mut y[..t.block_values()];
    let x = &x[..t.block_bytes()];
    match t {
        GgmlType::Q2K => {
            // scales[16] | qs[64] | d | dmin
            let (d, min) = (f16(x, 80), f16(x, 82));
            let mut o = 0;
            let mut is = 0;
            for n in 0..2 {
                let q = &x[16 + 32 * n..];
                for j in 0..4 {
                    let shift = 2 * j;
                    for half in 0..2 {
                        let sc = x[is];
                        is += 1;
                        let (dl, ml) = (d * f32::from(sc & 0xf), min * f32::from(sc >> 4));
                        for l in 0..16 {
                            y[o] = dl * f32::from((q[l + 16 * half] >> shift) & 3) - ml;
                            o += 1;
                        }
                    }
                }
            }
        }
        GgmlType::Q4K => {
            // d | dmin | scales[12] | qs[128]
            let (d, min) = (f16(x, 0), f16(x, 2));
            let scales = &x[4..16];
            for c in 0..4 {
                let q = &x[16 + 32 * c..];
                let (sc1, m1) = scale_min_k4(2 * c, scales);
                let (sc2, m2) = scale_min_k4(2 * c + 1, scales);
                let (d1, m1) = (d * f32::from(sc1), min * f32::from(m1));
                let (d2, m2) = (d * f32::from(sc2), min * f32::from(m2));
                for l in 0..32 {
                    y[64 * c + l] = d1 * f32::from(q[l] & 0xf) - m1;
                    y[64 * c + 32 + l] = d2 * f32::from(q[l] >> 4) - m2;
                }
            }
        }
        GgmlType::Iq2Xxs => {
            // d | qs[32] (u16): per 32 values, 4 grid bytes then a u32 of 4 x 7 sign bits + scale.
            let d = f16(x, 0);
            for ib in 0..8 {
                let (a0, a1) = (u32_at(x, 2 + 8 * ib), u32_at(x, 6 + 8 * ib));
                let db = d * (0.5 + (a1 >> 28) as f32) * 0.25;
                for l in 0..4 {
                    let grid = IQ2XXS_GRID[((a0 >> (8 * l)) & 0xff) as usize];
                    let signs = KSIGNS_IQ2XS[((a1 >> (7 * l)) & 127) as usize];
                    for j in 0..8 {
                        y[32 * ib + 8 * l + j] =
                            db * f32::from(grid_byte(grid, j)) * sign(signs, j);
                    }
                }
            }
        }
        GgmlType::Iq2Xs => {
            // d | qs[32] (u16: 9-bit grid index, 7-bit sign index) | scales[8]
            let d = f16(x, 0);
            for ib in 0..8 {
                let s = x[66 + ib];
                let db = [
                    d * (0.5 + f32::from(s & 0xf)) * 0.25,
                    d * (0.5 + f32::from(s >> 4)) * 0.25,
                ];
                for l in 0..4 {
                    let q = u16_at(x, 2 + 2 * (4 * ib + l));
                    let grid = IQ2XS_GRID[usize::from(q & 511)];
                    let signs = KSIGNS_IQ2XS[usize::from(q >> 9)];
                    for j in 0..8 {
                        y[32 * ib + 8 * l + j] =
                            db[l / 2] * f32::from(grid_byte(grid, j)) * sign(signs, j);
                    }
                }
            }
        }
        GgmlType::Iq2S => {
            // d | qs[32] | signs[32] | qh[8] | scales[8]
            let d = f16(x, 0);
            for ib in 0..8 {
                let s = x[74 + ib];
                let db = [
                    d * (0.5 + f32::from(s & 0xf)) * 0.25,
                    d * (0.5 + f32::from(s >> 4)) * 0.25,
                ];
                let qh = usize::from(x[66 + ib]);
                for l in 0..4 {
                    let idx = usize::from(x[2 + 4 * ib + l]) | ((qh << (8 - 2 * l)) & 0x300);
                    let grid = IQ2S_GRID[idx];
                    let signs = x[34 + 4 * ib + l];
                    for j in 0..8 {
                        y[32 * ib + 8 * l + j] =
                            db[l / 2] * f32::from(grid_byte(grid, j)) * sign(signs, j);
                    }
                }
            }
        }
        GgmlType::Iq3Xxs => {
            // d | qs[64] grid bytes | 8 u32 of 4 x 7 sign bits + 4-bit scale
            let d = f16(x, 0);
            for ib in 0..8 {
                let aux = u32_at(x, 66 + 4 * ib);
                let db = d * (0.5 + (aux >> 28) as f32) * 0.5;
                for l in 0..4 {
                    let signs = KSIGNS_IQ2XS[((aux >> (7 * l)) & 127) as usize];
                    let g1 =
                        u64::from(crate::format::IQ3_XXS_GRID[usize::from(x[2 + 8 * ib + 2 * l])]);
                    let g2 =
                        u64::from(crate::format::IQ3_XXS_GRID[usize::from(x[3 + 8 * ib + 2 * l])]);
                    for j in 0..4 {
                        let o = 32 * ib + 8 * l;
                        y[o + j] = db * f32::from(grid_byte(g1, j)) * sign(signs, j);
                        y[o + j + 4] = db * f32::from(grid_byte(g2, j)) * sign(signs, j + 4);
                    }
                }
            }
        }
        GgmlType::Iq3S => {
            // d | qs[64] | qh[8] | signs[32] | scales[4]
            let d = f16(x, 0);
            for ib in 0..8 {
                let s = x[106 + ib / 2];
                let db = d * f32::from(1 + 2 * if ib % 2 == 0 { s & 0xf } else { s >> 4 });
                let qh = usize::from(x[66 + ib]);
                for l in 0..4 {
                    let q0 = usize::from(x[2 + 8 * ib + 2 * l]) | ((qh << (8 - 2 * l)) & 256);
                    let q1 = usize::from(x[3 + 8 * ib + 2 * l]) | ((qh << (7 - 2 * l)) & 256);
                    let (g1, g2) = (u64::from(IQ3S_GRID[q0]), u64::from(IQ3S_GRID[q1]));
                    let signs = x[74 + 4 * ib + l];
                    for j in 0..4 {
                        let o = 32 * ib + 8 * l;
                        y[o + j] = db * f32::from(grid_byte(g1, j)) * sign(signs, j);
                        y[o + j + 4] = db * f32::from(grid_byte(g2, j)) * sign(signs, j + 4);
                    }
                }
            }
        }
        GgmlType::Iq1M => {
            // qs[32] | qh[16] | scales[8] (four u16: 3-bit sub-scales; top nibbles form the f16 d)
            let sc = [u16_at(x, 48), u16_at(x, 50), u16_at(x, 52), u16_at(x, 54)];
            let dbits = (sc[0] >> 12)
                | ((sc[1] >> 8) & 0x00f0)
                | ((sc[2] >> 4) & 0x0f00)
                | (sc[3] & 0xf000);
            let d = crate::format::f16_to_f32(dbits);
            const DELTA: f32 = 0.125;
            for ib in 0..8 {
                let w = sc[ib / 2];
                let dl1 = d * f32::from(2 * ((w >> (6 * (ib % 2))) & 7) + 1);
                let dl2 = d * f32::from(2 * ((w >> (6 * (ib % 2) + 3)) & 7) + 1);
                let (qs, qh) = (&x[4 * ib..], &x[32 + 2 * ib..]);
                let idx = [
                    usize::from(qs[0]) | ((usize::from(qh[0]) << 8) & 0x700),
                    usize::from(qs[1]) | ((usize::from(qh[0]) << 4) & 0x700),
                    usize::from(qs[2]) | ((usize::from(qh[1]) << 8) & 0x700),
                    usize::from(qs[3]) | ((usize::from(qh[1]) << 4) & 0x700),
                ];
                let delta = [
                    if qh[0] & 0x08 != 0 { -DELTA } else { DELTA },
                    if qh[0] & 0x80 != 0 { -DELTA } else { DELTA },
                    if qh[1] & 0x08 != 0 { -DELTA } else { DELTA },
                    if qh[1] & 0x80 != 0 { -DELTA } else { DELTA },
                ];
                for l in 0..4 {
                    let dl = if l < 2 { dl1 } else { dl2 };
                    let grid = IQ1S_GRID[idx[l]];
                    for j in 0..8 {
                        let g = f32::from(grid_byte(grid, j) as i8);
                        y[32 * ib + 8 * l + j] = dl * (g + delta[l]);
                    }
                }
            }
        }
        GgmlType::Iq4Xs => {
            // d | scales_h (u16) | scales_l[4] | qs[128]
            let d = f16(x, 0);
            let sh = u16_at(x, 2);
            for ib in 0..8 {
                let ls = i32::from((x[4 + ib / 2] >> (4 * (ib % 2))) & 0xf)
                    | (i32::from((sh >> (2 * ib)) & 3) << 4);
                let dl = d * (ls - 32) as f32;
                let qs = &x[8 + 16 * ib..];
                for j in 0..16 {
                    y[32 * ib + j] = dl * f32::from(KVALUES_IQ4NL[usize::from(qs[j] & 0xf)]);
                    y[32 * ib + 16 + j] = dl * f32::from(KVALUES_IQ4NL[usize::from(qs[j] >> 4)]);
                }
            }
        }
        GgmlType::Q2_0 => {
            // d | qs[16]: 2 bits per value, codes 0..3 meaning -1, 0, +1, +2
            let d = f16(x, 0);
            for (j, v) in y.iter_mut().enumerate() {
                let q = (x[2 + j / 4] >> (2 * (j % 4))) & 3;
                *v = (i32::from(q) - 1) as f32 * d;
            }
        }
        GgmlType::Iq4Nl => {
            // d | qs[16]
            let d = f16(x, 0);
            for j in 0..16 {
                y[j] = d * f32::from(KVALUES_IQ4NL[usize::from(x[2 + j] & 0xf)]);
                y[j + 16] = d * f32::from(KVALUES_IQ4NL[usize::from(x[2 + j] >> 4)]);
            }
        }
        GgmlType::Q6K => {
            // ql[128] | qh[64] | scales[16] (i8) | d
            let d = f16(x, 208);
            for n in 0..2 {
                let (ql, qh, scales) = (&x[64 * n..], &x[128 + 32 * n..], &x[192 + 8 * n..]);
                let sc = |i: usize| f32::from(scales[i] as i8);
                for l in 0..32 {
                    let is = l / 16;
                    let q1 = ((ql[l] & 0xf) | ((qh[l] & 3) << 4)) as i8 - 32;
                    let q2 = ((ql[l + 32] & 0xf) | (((qh[l] >> 2) & 3) << 4)) as i8 - 32;
                    let q3 = ((ql[l] >> 4) | (((qh[l] >> 4) & 3) << 4)) as i8 - 32;
                    let q4 = ((ql[l + 32] >> 4) | (((qh[l] >> 6) & 3) << 4)) as i8 - 32;
                    let o = 128 * n + l;
                    y[o] = d * sc(is) * f32::from(q1);
                    y[o + 32] = d * sc(is + 2) * f32::from(q2);
                    y[o + 64] = d * sc(is + 4) * f32::from(q3);
                    y[o + 96] = d * sc(is + 6) * f32::from(q4);
                }
            }
        }
        GgmlType::Q8_0 => {
            // d | qs[32] (i8)
            let d = f16(x, 0);
            for (j, v) in y.iter_mut().enumerate() {
                *v = f32::from(x[2 + j] as i8) * d;
            }
        }
    }
}

/// Decodes `rows` rows from `row_begin` of a `[n, k]` parent into `out` (`[rows, k]` appended).
pub fn decode_rows_into(
    t: GgmlType,
    payload: &[u8],
    k: usize,
    row_begin: usize,
    rows: usize,
    out: &mut Vec<f32>,
) {
    let (rb, bb, bv) = (t.row_bytes(k), t.block_bytes(), t.block_values());
    let start = out.len();
    out.resize(start + rows * k, 0.0);
    for (i, row) in out[start..].chunks_exact_mut(k).enumerate() {
        let bytes = &payload[(row_begin + i) * rb..(row_begin + i + 1) * rb];
        for (b, vals) in row.chunks_exact_mut(bv).enumerate() {
            decode_block(t, &bytes[b * bb..(b + 1) * bb], vals);
        }
    }
}

/// Byte offsets of a block's binary16 scale fields (for IQ1_M the super-scale lives in the top
/// nibbles of its four scale words instead; see [`random_block`]).
pub fn scale_fields(t: GgmlType) -> &'static [usize] {
    match t {
        GgmlType::Q2K => &[80, 82],
        GgmlType::Q4K => &[0, 2],
        GgmlType::Q6K => &[208],
        GgmlType::Iq1M => &[],
        _ => &[0],
    }
}

/// Fills `block` from `bytes` (random code bytes) and sets its scales to the binary16 values
/// `scales` yields: every code pattern of every type is legal, only the scales need to stay finite.
pub fn random_block(
    t: GgmlType,
    block: &mut [u8],
    mut bytes: impl FnMut() -> u8,
    mut scale: impl FnMut() -> u16,
) {
    for b in block.iter_mut() {
        *b = bytes();
    }
    for &off in scale_fields(t) {
        block[off..off + 2].copy_from_slice(&scale().to_le_bytes());
    }
    if t == GgmlType::Iq1M {
        let h = scale();
        for j in 0..4 {
            let o = 48 + 2 * j + 1;
            block[o] = (block[o] & 0x0f) | ((((h >> (4 * j)) & 0xf) as u8) << 4);
        }
    }
}

